// B23 boundary: h = f(p) using 5-segment cubic polynomials
// Relative pressure: pr = p / Ps_623
const PS_623: f64 = 1.652916425260450e+01;
const PC_WATER: f64 = 2.206400000000000e+01;

// Segment boundaries: [start, end] for each segment
const B23_P_BOUNDARIES: [(f64, f64); 5] = [
    (1.652916425260450e+01, 2.206400000000000e+01), // Segment 1
    (2.206400000000000e+01, 3.000000000000000e+01), // Segment 2
    (3.000000000000000e+01, 6.000000000000000e+01), // Segment 3
    (6.000000000000000e+01, 8.000000000000000e+01), // Segment 4
    (8.000000000000000e+01, 1.000000000000000e+02), // Segment 5
];

// Coefficients for h = a3*pr^3 + a2*pr^2 + a1*pr + a0
const B23_COEFFS: [[f64; 4]; 5] = [
    // Segment 1: 16.5292 ~ 22.1 MPa
    [2.989002073304363e+03, -1.130323920766207e+04, 1.427839316806028e+04, -3.400564029814132e+03],
    // Segment 2: 22.0640 ~ 30.0 MPa
    [1.305674800103026e+02, -6.409849124900450e+02, 1.009861711046295e+03, 2.109968798085634e+03],
    // Segment 3: 30.0000 ~ 60.0 MPa
    [-9.082901863771234e+00, 9.884879287798601e+01, -3.031425639140778e+02, 2.890742683870103e+03],
    // Segment 4: 60.0000 ~ 80.0 MPa
    [-1.087275078402145e+00, 1.675713963325019e+01, -2.093754097329930e+01, 2.565758409775885e+03],
    // Segment 5: 80.0000 ~ 100.0 MPa
    [-5.827531873662035e-01, 9.469510372197281e+00, 1.440298433057236e+01, 2.508235587031571e+03],
];

/// B23 boundary enthalpy h = f(p) in kJ/kg
/// p: pressure in MPa
pub fn b23_p2h(p: f64) -> f64 {
    let pr = p / PS_623;
    for i in 0..5 {
        if p >= B23_P_BOUNDARIES[i].0 && p <= B23_P_BOUNDARIES[i].1 {
            let c = &B23_COEFFS[i];
            return ((c[0]*pr + c[1])*pr + c[2])*pr + c[3];
        }
    }
    f64::NAN
}